function getSvDateKey(offsetDays = 0): string {
  const now = new Date();
  const svNow = new Date(now.getTime() - 6 * 60 * 60 * 1000);
  svNow.setUTCDate(svNow.getUTCDate() + offsetDays);
  const y = svNow.getUTCFullYear();
  const m = String(svNow.getUTCMonth() + 1).padStart(2, '0');
  const d = String(svNow.getUTCDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

function getSvIso(offsetDays = 0, hour = 10, minute = 15): string {
  const key = getSvDateKey(offsetDays);
  const hh = String(Math.max(0, Math.min(23, hour))).padStart(2, '0');
  const mm = String(Math.max(0, Math.min(59, minute))).padStart(2, '0');
  return `${key}T${hh}:${mm}:00-06:00`;
}

function getCurrentMonthPrefix(): string {
  return getSvDateKey(0).slice(0, 7);
}

